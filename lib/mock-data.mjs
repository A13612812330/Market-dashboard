function makeIndex(name, code, value, changePct, changePoint, trend, windows) {
  const keys = ["today", "five", "day", "month", "quarter", "year", "all"];
  return {
    name,
    code,
    value,
    change_pct: changePct,
    change_point: changePoint,
    trend,
    updated_at: now(),
    windows: Object.fromEntries(keys.map((key, index) => [key, windows[index]]))
  };
}

function stock(code, name, sector, volumeRatio, turnoverRate, changePct, amount, marketCap, price, amplitude, time) {
  return {
    code,
    name,
    sector,
    volume_ratio: volumeRatio,
    turnover_rate: turnoverRate,
    change_pct: changePct,
    amount,
    float_market_cap: Math.round(marketCap * 0.62),
    market_cap: marketCap,
    price,
    amplitude,
    update_time: time
  };
}

function etf(code, name, category, price, changePct, amount, netInflow, tracking, time) {
  return {
    code,
    name,
    category,
    price,
    change_pct: changePct,
    amount,
    net_inflow: netInflow * 100_000_000,
    tracking,
    update_time: time
  };
}

function sectorFlow(name, changePct, netInflow, upCount, downCount, leaders, signal) {
  return {
    name,
    change_pct: changePct,
    net_inflow: netInflow,
    up_count: upCount,
    down_count: downCount,
    leaders,
    signal,
    updated_at: now()
  };
}

